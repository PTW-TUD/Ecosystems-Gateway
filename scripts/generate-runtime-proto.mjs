// Writes the runtime protos the gRPC server and the HTTP gateway load: each proto of
// src/_proto without its protoc-gen-openapiv2 annotations, which @grpc/proto-loader cannot
// resolve (buf fetches them from the Buf Schema Registry). Run by `npm run proto:gen`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
export const SOURCE_DIR = join(ROOT, 'src/_proto');
export const RUNTIME_DIR = join(ROOT, 'src/_proto_runtime');

/** The runtime proto for the proto `source` read from `file` (relative to the repository). */
export function toRuntimeProto(source, file) {
  const header =
    `// Generated by npm run proto:gen from ${file}. Do not edit: change ${file} and\n` +
    `// regenerate. It leaves out the OpenAPI annotations, which @grpc/proto-loader cannot load.\n\n`;
  return header + stripOpenapiAnnotations(source);
}

/** Removes the `protoc_gen_openapiv2` options and import, keeping everything else as written. */
export function stripOpenapiAnnotations(source) {
  const option =
    /[ \t]*option\s*\(grpc\.gateway\.protoc_gen_openapiv2[^)]*\)\s*=\s*\{/g;
  let result = '';
  let from = 0;
  let match;
  while ((match = option.exec(source))) {
    result += source.slice(from, match.index);
    let depth = 1;
    let index = match.index + match[0].length;
    let inString = false;
    for (; index < source.length && depth > 0; index++) {
      const char = source[index];
      if (inString) {
        if (char === '\\') index++;
        else if (char === '"') inString = false;
      } else if (char === '"') inString = true;
      else if (char === '{') depth++;
      else if (char === '}') depth--;
    }
    // the closing `;` and the rest of the line, unless it holds more than whitespace
    const rest = /^;?[ \t]*(\r?\n)?/.exec(source.slice(index));
    index += rest[0].length;
    from = option.lastIndex = index;
  }
  result += source.slice(from);
  return result
    .replace(/^import "protoc-gen-openapiv2\/[^"]*";\r?\n/gm, '')
    .replace(/\n{3,}/g, '\n\n');
}

/** Each proto of src/_proto and the runtime proto it gives. */
export function runtimeProtos() {
  return readdirSync(SOURCE_DIR)
    .filter((name) => name.endsWith('.proto'))
    .map((name) => {
      const file = `src/_proto/${name}`;
      return {
        source: file,
        target: join(RUNTIME_DIR, `${basename(name, '.proto')}.runtime.proto`),
        content: toRuntimeProto(
          readFileSync(join(SOURCE_DIR, name), 'utf8'),
          file,
        ),
      };
    });
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { target, content } of runtimeProtos()) {
    writeFileSync(target, content);
    console.log(`wrote ${relative(ROOT, target)}`);
  }
}
